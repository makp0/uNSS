#pragma once

#include <string>


// 백그라운드 자동 백업을 담당하는 sysmodule 의 설치를 관리한다.
//
// 모듈 자체는 NRO 의 romfs 에 들어있다. Atmosphere 는
// atmosphere/contents/<PROGRAM_ID>/ 만 인식하므로 그 위치로 풀어준다.
namespace sysmodule
{

// config.json 의 program_id 와 반드시 같아야 한다.
//
// 0x0100... 대역은 시스템 모듈용으로 0x...0FFF 정도까지만 쓰인다.
// 그보다 높은 값은 애플리케이션으로 취급돼 boot2 가 아예 띄우지 않는다.
// 그래서 sys-patch(420000000000000B), nx-ovlloader(420000000007E51A) 와
// 같은 0x42 대역을 쓴다. 이 콘솔에서 실제로 도는 것이 확인된 대역이다.
constexpr const char* PROGRAM_ID = "4200000000554E53";

// romfs 에 들어있는 모듈의 버전. 모듈을 고칠 때마다 올린다.
// 3: 부팅 직후에 서비스를 열지 않도록 고쳤다. 2 는 HID 를 죽여서 콘솔을
//    부팅 루프에 빠뜨렸다 (2001-0132, 커널 LimitReached).
// 4: smExit() 전에 pm:dmnt 를 열어둔다. 3 에서는 "게임 중에는 백업하지
//    않는다" 는 보호가 아예 동작하지 않았다.
// 5: 올릴 것이 있는지 먼저 확인하고, 있을 때만 네트워크를 연다.
// 6: 한 번 돌고 끝나지 않고 계속 살아 있는다. 게임이 끝나면 백업한다.
//    5 까지는 부팅 때만 돌았고, 스위치는 재부팅을 거의 하지 않는다.
// 7: NsApplicationControlData 를 스택이 아니라 힙에 둔다. 144KB 짜리라
//    16KB 스택에서는 함수 프롤로그에서 바로 넘쳤다. 6 은 백업을 시작하는
//    순간 반드시 죽었다 (2168-0002 data abort, getTitleName+0x8).
//    자기 보호도 고쳤다: 6 까지는 첫 바퀴만 감시해서, 정작 위험한 백업
//    도중의 죽음은 아무도 알아채지 못했다.
// 8: smExit() 앞에서 ssl 서비스를 연다. libcurl 은 첫 https 연결에서야
//    ssl 을 게을리 여는데, 그 시점에는 SM 세션이 이미 없어 실패했다.
//    7 은 죽지 않았지만 push 가 한 번도 성공하지 못했고, 서버 로그에는
//    아무 흔적도 남지 않았다 - 바이트가 나간 적이 없기 때문이다.
//    실패 로그에 실제 원인 코드도 함께 남긴다 (ret=-1 만으로는 못 찾는다).
// 9: smExit() 를 아예 부르지 않는다. 8 은 ssl 만 미리 열었는데, 정작
//    먼저 걸리는 것은 이름 풀이였다. sfdnsres 에는 초기화 함수가 없고
//    요청마다 SM 으로 서비스를 여므로, SM 을 닫으면 getaddrinfo 가
//    실패한다 (http=-4, CURLE_COULDNT_RESOLVE_HOST 로 확인).
//    미리 잡아두던 ssl 세션 두 개도 도로 뺐다 - 8 을 넣은 직후 am 이
//    2001-0132 로 죽었다. 자기 보호도 조인다: 콘솔 전체가 내려앉는
//    사고는 백업 실패와 같은 무게로 다루지 않는다.
// 10: 힙을 2 MiB 에서 1 MiB 로 줄인다. 2 MiB 도 컸다 - sys-ftpd 가 같은
//     풀에서 함께 뜨기 시작한 날, am 이 2001-0132 로 세 번 죽었다
//     (세 번 다 PC-start = 0x390b4, 매번 우리가 뜬 뒤 30 초 안).
//     크기는 쓰는 만큼이 아니라 잡은 만큼 풀에서 빠진다.
//     한 바퀴의 실사용량을 이제 로그에 남긴다 - 다음 값은 재고 정한다.
// 11: 고치는 대신 잰다. 힙을 6 -> 2 -> 1 MiB 로 줄이는 동안 am 은 매번
//     똑같이 죽었다 - 우리가 뜬 뒤 4-6 초에, 네 번 모두. 크기를 또 짐작할
//     일이 아니다. 커널이 세는 다섯 가지 한계 (메모리, 스레드, 이벤트,
//     전송 메모리, 세션) 와 네 개의 메모리 풀을 시작할 때 적고, 그 뒤
//     5 초마다 다시 적는다. 죽는 순간이 그 구간 안에 있으므로, 다음 사고
//     때는 어느 통이 비었는지가 로그에 남는다.
// 12: 계정마다 자기 세이브만 본다. 세이브 목록은 콘솔 전체를 사용자 구분
//     없이 돌려주는데 거르지 않았다 - 그래서 계정 셋이 똑같은 26 개를 받고,
//     남의 세이브를 열려다 스물세 번씩 실패했다. 고장이 아니라 "그 계정에는
//     없다" 였다. 같은 게임이 로그에 세 번 찍히던 것도 같은 이유였다.
//     "세이브 없음" 을 실패와 구별한다 - 실패로 세면 한 바퀴가 늘 오류로
//     끝나고, 마지막 성공 시각이 남지 않아 다음 바퀴가 전부를 다시 한다.
//     힙은 1 MiB -> 256 KB. 실측 최고점이 189 KB 였다 (2026-08-01).
// 13: 힙을 1 MiB 로 되돌린다. 12 에서 256 KB 로 줄인 것은 실측 최고점
//     189 KB 를 하한으로 읽은 탓인데, 그 값은 힙 크기에 따라 움직인다 -
//     256 KB 에서는 같은 일에 245 KB 를 썼고, 압축과 이름 조회와 업로드가
//     한꺼번에 무너졌다. 계정 필터는 12 에서 확인됐으므로 그대로 둔다
//     (올릴 타이틀이 78 개에서 26 개로 줄었다).
constexpr int BUNDLED_VERSION = 20;


enum class State
{
    NotInstalled,   // 설치된 적 없음
    Outdated,       // 설치돼 있지만 NRO 가 들고 있는 것이 더 새것
    UpToDate,       // 최신
    Interrupted,    // 설치돼 있지만 지난 실행이 끝까지 가지 못해 꺼져 있음
};


State getState();

// 치워둔 boot2 플래그를 제자리로 돌린다 (State::Interrupted 일 때).
//
// 모듈은 위험한 일을 하기 전에 플래그를 치우고 무사히 끝나면 되돌린다.
// 그래서 모듈이 죽어도 부팅 루프가 생기지 않지만, 백업 도중에 콘솔을 끈
// 경우에도 똑같이 치워진 채로 남는다. 둘을 구별할 방법이 없으므로 되살리는
// 것은 사용자가 정한다. 성공하면 0.
int resume();

// romfs 의 모듈을 atmosphere/contents 로 복사하고 boot2 플래그를 만든다.
// 성공하면 0.
int install();

// 설치한 파일들을 지운다. 성공하면 0.
int uninstall();

// 사용자에게 보여줄 설치 경로.
std::string installPath();

}
